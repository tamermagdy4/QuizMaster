questions = []
for line in raw.split('\n'):
    line = line.strip()
    if not line:
        continue
    parts = line.split('\t')
    if len(parts) < 3:
        continue
    # Strip number prefix
    q = parts[1].strip()
    a = parts[2].strip()
    questions.append((q, a))

print(f"Parsed {len(questions)} questions")

# Build JSON
